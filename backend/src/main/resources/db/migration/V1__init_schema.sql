CREATE TABLE products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku_code VARCHAR(20) NOT NULL UNIQUE,
    erp_code VARCHAR(30) NOT NULL,
    name VARCHAR(120) NOT NULL,
    short_name VARCHAR(60) NOT NULL,
    unit_of_measure VARCHAR(10) NOT NULL DEFAULT 'SA',
    units_per_box INT NOT NULL DEFAULT 10,
    physical_stock INT NOT NULL DEFAULT 0,
    reserved_stock INT NOT NULL DEFAULT 0,
    current_landed_cost DECIMAL(12, 2) NOT NULL,
    base_list_price DECIMAL(12, 2) NOT NULL,
    ncm VARCHAR(8) NOT NULL,
    cest VARCHAR(10),
    c_benef VARCHAR(20),
    origin_code INT NOT NULL DEFAULT 1,
    default_cfop_internal VARCHAR(4) NOT NULL DEFAULT '5102',
    default_cfop_interstate VARCHAR(4) NOT NULL DEFAULT '6102',
    estimated_tax_rate DECIMAL(5, 2) NOT NULL DEFAULT 12.00
);

CREATE TABLE import_batches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_code VARCHAR(40) NOT NULL UNIQUE,
    arrival_date DATE NOT NULL,
    supplier_name VARCHAR(120),
    exchange_rate_usd DECIMAL(10, 4) NOT NULL,
    fob_total_usd DECIMAL(14, 2) NOT NULL,
    international_freight_brl DECIMAL(14, 2) NOT NULL,
    import_taxes_brl DECIMAL(14, 2) NOT NULL,
    customs_expenses_brl DECIMAL(14, 2) NOT NULL,
    total_landed_cost_brl DECIMAL(14, 2) NOT NULL,
    notes VARCHAR(500)
);

CREATE TABLE import_batch_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL REFERENCES import_batches(id) ON DELETE CASCADE,
    product_id BIGINT NOT NULL REFERENCES products(id),
    quantity_imported INT NOT NULL,
    fob_unit_usd DECIMAL(12, 2) NOT NULL,
    calculated_unit_cost_brl DECIMAL(12, 2) NOT NULL
);

CREATE TABLE clients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    corporate_name VARCHAR(160) NOT NULL,
    trade_name VARCHAR(120),
    cnpj VARCHAR(18),
    state_registration VARCHAR(30),
    ie_indicator VARCHAR(30) NOT NULL DEFAULT 'CONTRIBUINTE',
    purchase_profile VARCHAR(30) NOT NULL DEFAULT 'INDUSTRIALIZACAO',
    zip_code VARCHAR(12),
    street VARCHAR(160),
    number VARCHAR(20),
    complement VARCHAR(60),
    neighborhood VARCHAR(80),
    city VARCHAR(80) DEFAULT 'São Paulo',
    state VARCHAR(2) DEFAULT 'SP',
    ibge_city_code VARCHAR(7),
    contact_name VARCHAR(80),
    phone VARCHAR(30),
    default_payment_terms VARCHAR(60) DEFAULT 'Boleto 28 dias',
    average_purchase_cycle_days INT NOT NULL DEFAULT 20,
    last_purchase_date DATE,
    last_order_total DECIMAL(12, 2) DEFAULT 0.00,
    financial_status VARCHAR(30) NOT NULL DEFAULT 'EM_DIA',
    is_registration_complete BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE client_sku_prices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id BIGINT NOT NULL REFERENCES clients(id) ON DELETE CASCADE,
    product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    last_practiced_price DECIMAL(12, 2) NOT NULL,
    agreed_standard_price DECIMAL(12, 2) NOT NULL,
    last_order_date DATE,
    CONSTRAINT uk_client_product UNIQUE (client_id, product_id)
);

CREATE TABLE client_notes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id BIGINT NOT NULL REFERENCES clients(id) ON DELETE CASCADE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    content VARCHAR(1000) NOT NULL
);

CREATE TABLE visit_schedules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id BIGINT NOT NULL REFERENCES clients(id) ON DELETE CASCADE,
    scheduled_date DATE NOT NULL,
    scheduled_time VARCHAR(10) NOT NULL,
    reminder_note VARCHAR(300),
    status VARCHAR(30) NOT NULL DEFAULT 'PENDENTE'
);

CREATE TABLE orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id BIGINT NOT NULL REFERENCES clients(id),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(30) NOT NULL,
    payment_terms VARCHAR(60) NOT NULL,
    delivery_forecast VARCHAR(80),
    notes_for_invoice_or_driver VARCHAR(500),
    backoffice_adjustment_notes VARCHAR(500),
    shipping_cost_estimate DECIMAL(12, 2) NOT NULL DEFAULT 45.00,
    original_commercial_total DECIMAL(12, 2) NOT NULL DEFAULT 0.00,
    gross_total DECIMAL(12, 2) NOT NULL DEFAULT 0.00,
    total_cmv_snapshot DECIMAL(12, 2) NOT NULL DEFAULT 0.00,
    estimated_tax_snapshot DECIMAL(12, 2) NOT NULL DEFAULT 0.00,
    net_profit_snapshot DECIMAL(12, 2) NOT NULL DEFAULT 0.00,
    net_margin_percentage DECIMAL(6, 2) NOT NULL DEFAULT 0.00,
    nfe_status VARCHAR(30) DEFAULT 'PENDENTE',
    nfe_number VARCHAR(20),
    nfe_access_key VARCHAR(44),
    danfe_pdf_url VARCHAR(255),
    xml_url VARCHAR(255),
    sefaz_rejection_message VARCHAR(500)
);

CREATE TABLE order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    product_id BIGINT NOT NULL REFERENCES products(id),
    ordered_quantity INT NOT NULL,
    quantity INT NOT NULL,
    ordered_unit_price DECIMAL(12, 2) NOT NULL,
    unit_sale_price DECIMAL(12, 2) NOT NULL,
    unit_cost_snapshot DECIMAL(12, 2) NOT NULL,
    is_promotional_price BOOLEAN NOT NULL DEFAULT FALSE
);
