CREATE TABLE receivable_titles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT REFERENCES orders(id) ON DELETE SET NULL,
    client_id BIGINT NOT NULL REFERENCES clients(id) ON DELETE CASCADE,
    client_name VARCHAR(160) NOT NULL,
    document_number VARCHAR(60) NOT NULL,
    installment_number INT NOT NULL DEFAULT 1,
    total_installments INT NOT NULL DEFAULT 1,
    amount_bq DECIMAL(12, 2) NOT NULL,
    due_date DATE NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'ABERTO', -- ABERTO, PAGO, VENCIDO, CANCELADO
    paid_at TIMESTAMP,
    notes VARCHAR(500),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_name VARCHAR(100) NOT NULL,
    actor_role VARCHAR(60) NOT NULL,
    action_type VARCHAR(60) NOT NULL,
    target_entity VARCHAR(60) NOT NULL,
    target_id VARCHAR(60),
    summary VARCHAR(500) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Índices para performance
CREATE INDEX idx_receivables_client ON receivable_titles(client_id);
CREATE INDEX idx_receivables_order ON receivable_titles(order_id);
CREATE INDEX idx_receivables_status ON receivable_titles(status);
CREATE INDEX idx_receivables_due_date ON receivable_titles(due_date);
CREATE INDEX idx_audit_created ON audit_logs(created_at DESC);

